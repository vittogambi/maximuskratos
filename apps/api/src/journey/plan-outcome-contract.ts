import type { Indicator, ReviewCode } from './intervention/engine';
import { choicesForReview, type MemberReviewChoice } from './intervention/review-decision';

export type OutcomeCriterionStatus = 'PROVISIONAL' | 'CONFIRMED';
/** LEARNED belongs to exploration plans only. It is learning, not a measurable result. */
export type OutcomeAssessmentStatus = 'ACHIEVED' | 'NOT_YET' | 'INSUFFICIENT' | 'LEARNED';
/** EXPLORATION stores the question in soughtOutcome and the learning sought in criterion. */
export type OutcomeMode = 'RESULT' | 'EXPLORATION';

export type PlanOutcomeContract = {
  revision: number;
  mode: OutcomeMode;
  change: string;
  why: string | null;
  soughtOutcome: string;
  criterion: string;
  criterionStatus: OutcomeCriterionStatus;
  checkAt: string | null;
  evidenceHint: string | null;
  linkedIndicatorRef: string | null;
  purposeRevisionId: string | null;
  linkKind: string | null;
  effectiveFrom: string | null;
};

export type PlanOutcomeContractStore = {
  current: PlanOutcomeContract;
  history: PlanOutcomeContract[];
};

export type OutcomeAssessmentRow = {
  status: OutcomeAssessmentStatus;
  text: string | null;
  contractRevision: number;
  observedOn: string;
  periodStart: string | null;
};

const ASSESSMENT_STATUSES: OutcomeAssessmentStatus[] = ['ACHIEVED', 'NOT_YET', 'INSUFFICIENT', 'LEARNED'];

export function parseOutcomeContractStore(raw: unknown): PlanOutcomeContractStore | null {
  if (!raw || typeof raw !== 'object') return null;
  const record = raw as { current?: unknown; history?: unknown };
  const current = parseContract(record.current);
  if (!current) return null;
  const history = Array.isArray(record.history)
    ? record.history.map(parseContract).filter((row): row is PlanOutcomeContract => Boolean(row))
    : [];
  return { current, history };
}

export function parseContract(raw: unknown): PlanOutcomeContract | null {
  if (!raw || typeof raw !== 'object') return null;
  const row = raw as Record<string, unknown>;
  const soughtOutcome = typeof row.soughtOutcome === 'string' ? row.soughtOutcome.trim() : '';
  const criterion = typeof row.criterion === 'string' ? row.criterion.trim() : '';
  if (!soughtOutcome || !criterion) return null;
  const revision = typeof row.revision === 'number' && Number.isInteger(row.revision) ? row.revision : 1;
  return {
    revision,
    mode: row.mode === 'EXPLORATION' ? 'EXPLORATION' : 'RESULT',
    change: typeof row.change === 'string' ? row.change.trim() : soughtOutcome,
    why: typeof row.why === 'string' ? row.why.trim() || null : null,
    soughtOutcome,
    criterion,
    criterionStatus: row.criterionStatus === 'PROVISIONAL' ? 'PROVISIONAL' : 'CONFIRMED',
    checkAt: typeof row.checkAt === 'string' ? row.checkAt.slice(0, 10) : null,
    evidenceHint: typeof row.evidenceHint === 'string' ? row.evidenceHint.trim() || null : null,
    linkedIndicatorRef: typeof row.linkedIndicatorRef === 'string' ? row.linkedIndicatorRef.trim() || null : null,
    purposeRevisionId: typeof row.purposeRevisionId === 'string' ? row.purposeRevisionId.trim() || null : null,
    linkKind: typeof row.linkKind === 'string' ? row.linkKind.trim() || null : null,
    effectiveFrom: typeof row.effectiveFrom === 'string' ? row.effectiveFrom.slice(0, 10) : null,
  };
}

export function buildOutcomeContract(input: {
  mode?: OutcomeMode;
  change: string;
  why?: string | null;
  soughtOutcome: string;
  criterion: string;
  criterionStatus?: OutcomeCriterionStatus;
  checkAt?: string | null;
  evidenceHint?: string | null;
  linkedIndicatorRef?: string | null;
  purposeRevisionId?: string | null;
  linkKind?: string | null;
  effectiveFrom?: string | null;
  revision?: number;
}): PlanOutcomeContract {
  return {
    revision: input.revision ?? 1,
    mode: input.mode ?? 'RESULT',
    change: input.change.trim(),
    why: input.why?.trim() || null,
    soughtOutcome: input.soughtOutcome.trim(),
    criterion: input.criterion.trim(),
    criterionStatus: input.criterionStatus ?? 'CONFIRMED',
    checkAt: input.checkAt?.trim()?.slice(0, 10) || null,
    evidenceHint: input.evidenceHint?.trim() || null,
    linkedIndicatorRef: input.linkedIndicatorRef?.trim() || null,
    purposeRevisionId: input.purposeRevisionId?.trim() || null,
    linkKind: input.linkKind?.trim() || null,
    effectiveFrom: input.effectiveFrom?.trim()?.slice(0, 10) || null,
  };
}

export type OutcomeContractPendingField = 'CRITERION' | 'CRITERION_CONFIRM' | 'EVIDENCE' | 'CHECK_AT';

export type OutcomeContractMeta = {
  recoveredFromLegacy: boolean;
  complete: boolean;
  pendingFields: OutcomeContractPendingField[];
};

const AUTO_CRITERION_PREFIX = 'Reconozco que ocurrió cuando:';

export function isAutoGeneratedCriterion(criterion: string): boolean {
  return criterion.trim().startsWith(AUTO_CRITERION_PREFIX);
}

export function outcomeContractMeta(plan: {
  outcomeContract?: unknown;
  title: string;
  outcome: string;
  whyItMatters?: string | null;
  criterionText?: string | null;
  criterionStatus?: string | null;
  reviewAt?: Date | null;
  purposeRevisionId?: string | null;
  linkKind?: string | null;
}): OutcomeContractMeta {
  const hasStored = Boolean(parseOutcomeContractStore(plan.outcomeContract));
  const store = contractFromPlanRow(plan);
  if (!store) {
    return { recoveredFromLegacy: !hasStored, complete: false, pendingFields: ['CRITERION', 'CRITERION_CONFIRM', 'EVIDENCE', 'CHECK_AT'] };
  }
  const pending: OutcomeContractPendingField[] = [];
  const c = store.current;
  if (!c.soughtOutcome.trim()) pending.push('CRITERION');
  if (c.mode === 'RESULT') {
    if (c.criterionStatus === 'PROVISIONAL' || isAutoGeneratedCriterion(c.criterion)) pending.push('CRITERION_CONFIRM');
    if (!c.evidenceHint?.trim()) pending.push('EVIDENCE');
  }
  if (!c.checkAt?.trim()) pending.push('CHECK_AT');
  return {
    recoveredFromLegacy: !hasStored,
    complete: pending.length === 0,
    pendingFields: pending,
  };
}

export function contractFromPlanRow(plan: {
  title: string;
  outcome: string;
  whyItMatters?: string | null;
  criterionText?: string | null;
  criterionStatus?: string | null;
  reviewAt?: Date | null;
  purposeRevisionId?: string | null;
  linkKind?: string | null;
  outcomeContract?: unknown;
}): PlanOutcomeContractStore | null {
  const stored = parseOutcomeContractStore(plan.outcomeContract);
  if (stored) return stored;
  const criterion = plan.criterionText?.trim() || '';
  const sought = plan.outcome?.trim() || '';
  if (!sought) return null;
  const current = buildOutcomeContract({
    change: plan.title?.trim() || sought,
    why: plan.whyItMatters,
    soughtOutcome: sought,
    criterion: criterion || `${AUTO_CRITERION_PREFIX} ${sought}`,
    criterionStatus: 'PROVISIONAL',
    checkAt: plan.reviewAt ? plan.reviewAt.toISOString().slice(0, 10) : null,
    purposeRevisionId: plan.purposeRevisionId,
    linkKind: plan.linkKind,
  });
  return { current, history: [] };
}

/** Outcome assessment governs review explanation and strategy choices when present. */
export function mergeReviewWithOutcome(
  base: { code: ReviewCode; text: string },
  input: {
    assessment: OutcomeAssessmentStatus | null;
    executionLevel: string;
  },
): { code: ReviewCode; text: string; outcomeText: string; choices: MemberReviewChoice[] } {
  const execution = input.executionLevel === 'NOT_APPLICABLE' ? 'SUFFICIENT' : input.executionLevel;
  if (input.assessment === 'NOT_YET') {
    const outcomeText = execution === 'SUFFICIENT'
      ? 'Cumpliste lo acordado en acciones, pero el resultado que buscabas todavía no ocurrió. Completar tareas no demuestra que se haya logrado el cambio.'
      : 'El resultado que buscabas todavía no ocurrió. Revisa si la estrategia acerca al cambio o si falta evidencia.';
    return {
      code: execution === 'SUFFICIENT' ? 'CHECK' : 'EXPLORE',
      outcomeText,
      text: 'Conviene revisar la estrategia, el plazo o qué evidencia usas antes de subir la carga o declarar logro.',
      choices: ['MODIFY', 'SUBSTITUTE', 'REDUCE', 'KEEP'],
    };
  }
  if (input.assessment === 'ACHIEVED') {
    const outcomeText = execution === 'SUFFICIENT'
      ? 'Reconociste que el resultado que buscabas sí ocurrió.'
      : 'Reconociste que el resultado que buscabas sí ocurrió, aunque no hiciste todas las ocasiones acordadas.';
    return {
      code: execution === 'SUFFICIENT' ? 'KEEP' : 'LIGHTER_OK',
      outcomeText,
      text: 'Puedes mantener la estrategia, aligerar la carga o preparar cierre cuando lo decidas. No hace falta hacer más por hacer.',
      choices: ['KEEP', 'REDUCE'],
    };
  }
  if (input.assessment === 'LEARNED') {
    return {
      code: execution === 'SUFFICIENT' ? 'KEEP' : 'LIGHTER_OK',
      outcomeText: 'Registraste lo que aprendiste. Explorar no equivale a conseguir un resultado medible.',
      text: 'Puedes seguir explorando, ajustar la prueba o, si ya sabes qué quieres, cerrar este plan y diseñar uno con un resultado concreto.',
      choices: ['KEEP', 'MODIFY', 'REDUCE'],
    };
  }
  if (input.assessment === 'INSUFFICIENT') {
    return {
      code: 'NO_RECORDS',
      outcomeText: 'Todavía no hay evidencia suficiente sobre el resultado que buscabas. Eso no es éxito ni fracaso.',
      text: 'Conviene aclarar qué observar o esperar al momento de comprobación antes de cambiar la estrategia.',
      choices: ['NO_RECORDS', 'KEEP'],
    };
  }
  return {
    ...base,
    outcomeText: '',
    choices: choicesForReview(base.code),
  };
}

export function digestOutcomeContract(store: PlanOutcomeContractStore | null, assessment: OutcomeAssessmentRow | null): string | null {
  if (!store) return null;
  return JSON.stringify({
    revision: store.current.revision,
    soughtOutcome: store.current.soughtOutcome,
    criterion: store.current.criterion,
    linkedIndicatorRef: store.current.linkedIndicatorRef,
    assessment: assessment
      ? { status: assessment.status, contractRevision: assessment.contractRevision, periodStart: assessment.periodStart }
      : null,
  });
}

export function reviseContract(
  store: PlanOutcomeContractStore,
  patch: Partial<PlanOutcomeContract> & { soughtOutcome?: string; criterion?: string },
  effectiveFrom: string,
): PlanOutcomeContractStore {
  const nextRevision = store.current.revision + 1;
  const next = buildOutcomeContract({
    ...store.current,
    ...patch,
    revision: nextRevision,
    effectiveFrom,
  });
  return { current: next, history: [...store.history, store.current] };
}

export function parseAssessmentStatus(value: unknown): OutcomeAssessmentStatus | null {
  if (typeof value !== 'string') return null;
  return ASSESSMENT_STATUSES.includes(value as OutcomeAssessmentStatus) ? (value as OutcomeAssessmentStatus) : null;
}

/** Suggest reusing tool RESULT indicator when the member criterion explicitly references the same observable question. */
export function suggestIndicatorLink(criterion: string, indicator: Indicator | null): string | null {
  if (!indicator || indicator.role !== 'RESULT') return null;
  const q = indicator.question.trim().toLowerCase();
  const c = criterion.trim().toLowerCase();
  if (!q || !c) return null;
  if (c.includes(q) || q.includes(c.slice(0, Math.min(24, c.length)))) return indicator.ref;
  return null;
}

export function outcomeCheckDue(contract: PlanOutcomeContract, today: string): 'NOT_YET' | 'DUE' | 'UNKNOWN' {
  if (!contract.checkAt) return 'UNKNOWN';
  return today >= contract.checkAt ? 'DUE' : 'NOT_YET';
}

export function reviewHintFromLayers(input: {
  executionLevel: string;
  coverage: string;
  assessment: OutcomeAssessmentStatus | null;
  checkDue: 'NOT_YET' | 'DUE' | 'UNKNOWN';
}): string {
  if (input.assessment === 'INSUFFICIENT' || (!input.assessment && input.checkDue === 'NOT_YET')) {
    return 'Todavía no hay información suficiente para juzgar el resultado que buscabas. Eso no es fracaso.';
  }
  if (input.assessment === 'NOT_YET' && input.executionLevel === 'SUFFICIENT') {
    return 'Hiciste lo acordado y el resultado propio todavía no se cumple. Revisa plazo, evidencia o estrategia, no solo la actividad.';
  }
  if (input.assessment === 'ACHIEVED' && input.executionLevel !== 'SUFFICIENT') {
    return 'El resultado que buscabas sí ocurrió aunque no hiciste todas las ocasiones. Puedes simplificar o preparar cierre.';
  }
  if (input.assessment === 'ACHIEVED') {
    return 'El resultado propio coincide con lo que buscabas. Puedes mantener o preparar cierre.';
  }
  if (input.assessment === 'LEARNED') {
    return 'Hay un aprendizaje registrado. No se cuenta como un resultado conseguido.';
  }
  return '';
}

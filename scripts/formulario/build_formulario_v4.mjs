const lensField = {
  Pasión: 'pasion',
  Vocación: 'vocacion',
  Misión: 'mision',
  Profesión: 'profesion',
};

for (const mod of catalog.modules) {
  if (profileOrder[mod.slug]) mod.order = profileOrder[mod.slug];
  if (Object.prototype.hasOwnProperty.call(intros, mod.slug)) {
    mod.introEs = intros[mod.slug];
  } else if (mod.introEs === mod.titleEs) {
    mod.introEs = '';
  }
  for (const question of mod.questions) {
    if (mod.slug === 'e-per-ikigai') {
      const named = /^@ikigai:([^:|]+)/.exec(question.contextEs ?? '');
      const lens = named?.[1];
      if (!lens || !lensField[lens]) throw new Error(`sin campo ${question.sourceRef} ${question.contextEs}`);
      question.contextEs = `@actividad:${lensField[lens]}`;
      continue;
    }
    if (question.contextEs && !question.contextEs.startsWith('@')) {
      question.contextEs = `@nota:${question.contextEs}`;
    }
  }
}

catalog.modules.sort((left, right) => left.order - right.order);
catalog.version = 'formulario-completo@5';
catalog.definitionRef = 'formulario-completo';
const hashed = { ...catalog };
delete hashed.sourceSha256;
delete hashed.definitionSha256;
catalog.definitionSha256 = createHash('sha256').update(JSON.stringify(hashed)).digest('hex');
writeFileSync('packages/database/definitions/formulario-completo@5.json', `${JSON.stringify(catalog, null, 2)}\n`);

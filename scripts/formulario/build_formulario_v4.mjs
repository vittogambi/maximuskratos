function cell(sheet, row, col) {
  const value = sheet[XLSX.utils.encode_cell({ r: row - 1, c: col })]?.v;
  return value == null ? '' : String(value).replace(/\s+/g, ' ').trim();
}

function columnIndex(letter) {
  return letter.charCodeAt(0) - 65;
}

function ambitsFromFormula(formula) {
  const pairs = [...formula.matchAll(/'NO BORRAR'!\$([A-Z])\$(\d+),\s*"'NO BORRAR'!([A-Z])(\d+):([A-Z])(\d+)"/g)];
  if (pairs.length < 4) throw new Error(`formula sin ámbitos: ${formula.slice(0, 80)}`);
  return pairs.map((match) => {
    const label = cell(noBorrar, Number(match[2]), columnIndex(match[1]));
    const start = Number(match[4]);
    const end = Number(match[6]);
    const optionCol = columnIndex(match[3]);
    const options = [];
    for (let row = start; row <= end; row += 1) {
      const option = cell(noBorrar, row, optionCol);
      if (option) options.push(option);
    }
    if (!label || options.length === 0) throw new Error(`ámbito vacío ${label}`);
    return { label, options };
  });
}

